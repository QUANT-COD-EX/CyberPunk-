"""
AI-Generated Document and Synthetic Content Forensics Engine.
Advisory output. Final decision rests with the human reviewer (ISO/IEC 27037).

Evaluates:
1. Direct AI generator boilerplates, prompt leakage, and disclaimers (ChatGPT, Claude, DALL-E, etc.)
2. Unfilled template placeholders and unrendered variable tags ([Insert ...], {{...}}, Lorem ipsum)
3. Stylometric uniformity & low burstiness (unnatural sentence length distributions)
4. Synthetic placeholder entity identifiers (mock PANs, sequential Aadhaar numbers, fictional entities)
5. PDF metadata generator software fingerprints (Canva Magic, v0.dev, Midjourney, etc.)
"""

import math
import re
from pathlib import Path
from typing import List, Optional, Tuple
import fitz  # PyMuPDF
from backend.app.models.contracts import (
    EvidenceItem,
    Finding,
    FindingCategory,
    FindingStatus,
    FindingStrength,
    FindingTier,
    ReviewerAction,
)

AI_BOILERPLATE_PATTERNS = [
    (r"\bas an ai language model\b", "Direct AI model disclaimer detected in document text"),
    (r"\bgenerated by (?:chatgpt|openai|claude|anthropic|midjourney|dall-e|copilot|gemini|deepseek)\b", "AI generator provenance tag detected in text"),
    (r"\bthis is a (?:simulated|fictitious|mock|synthetic|sample) document\b", "Synthetic / mock document disclaimer statement"),
    (r"\b(?:sample|simulated|synthetic) (?:bank statement|payslip|salary slip|loan application|form 15g|pan card|aadhaar)\b", "Synthetic instrument watermark / label"),
    (r"\[(?:insert|company name|employee name|employer name|date here|address here|amount here|account number here)\]", "Unfilled template placeholder token"),
    (r"\{\{[a-zA-Z0-9_\s]+\}\}|\$\{[a-zA-Z0-9_\s]+\}", "Unrendered template variable expression"),
    (r"\blorem ipsum dolor sit amet\b", "Standard placeholder dummy text (Lorem Ipsum)"),
]

AI_METADATA_PRODUCERS = [
    "canva magic",
    "midjourney",
    "dall-e",
    "stable diffusion",
    "chatgpt",
    "v0.dev",
    "synthetic",
]

SYNTHETIC_IDENTIFIER_PATTERNS = [
    (r"\b(?:ABCDE1234F|AAAAA0000A|XYZAB1234C|TESTP1234T)\b", "Known mock/placeholder PAN pattern"),
    (r"\b(?:1234\s?5678\s?9012|1111\s?2222\s?3333|0000\s?0000\s?0000)\b", "Sequential or repetitive mock Aadhaar sequence"),
    (r"\b(?:acme corp(?:oration)?|xyz corp(?:oration)?|global tech solutions inc|demo bank ltd|sample company)\b", "Generic fictional/placeholder entity moniker"),
]


def check_stylometric_uniformity(text: str) -> Tuple[bool, float, str]:
    """
    Computes sentence length distribution variance (burstiness).
    AI generated text typically exhibits unnaturally uniform sentence length.
    """
    sentences = [s.strip() for s in re.split(r"[.!?\n]+", text) if len(s.strip().split()) >= 4]
    if len(sentences) < 5:
        return False, 0.0, ""

    lengths = [len(s.split()) for s in sentences]
    avg_len = sum(lengths) / len(lengths)
    variance = sum((l - avg_len) ** 2 for l in lengths) / len(lengths)
    std_dev = math.sqrt(variance)

    # Natural human administrative/financial text has high burstiness (std_dev > 5.5).
    # Synthetic generator text often hovers around 10-18 words with std_dev < 2.0.
    if std_dev < 2.2 and 8.0 <= avg_len <= 26.0:
        return True, round(std_dev, 2), f"Unnatural sentence length uniformity (StdDev: {std_dev:.2f} words, Mean: {avg_len:.1f} words)"

    return False, round(std_dev, 2), ""


def detect_ai_generated_document(
    text: str,
    doc_path: Optional[Path],
    doc_id: str,
) -> Tuple[List[Finding], float, List[str], str]:
    """
    Inspects document text and PDF metadata for AI-generated hallmarks and synthetic artifacts.
    Returns: (findings, ai_risk_score, indicators, explanation)
    """
    findings: List[Finding] = []
    indicators: List[str] = []
    t_lower = text.lower()
    score_accum = 0.0

    # 1. AI Boilerplate & Disclaimers
    for pattern, desc in AI_BOILERPLATE_PATTERNS:
        match = re.search(pattern, t_lower, re.IGNORECASE)
        if match:
            score_accum += 0.55
            indicators.append(f"{desc}: '{match.group(0)}'")

    # 2. Synthetic Identifier & Entity Monikers
    for pattern, desc in SYNTHETIC_IDENTIFIER_PATTERNS:
        match = re.search(pattern, text, re.IGNORECASE)
        if match:
            score_accum += 0.35
            indicators.append(f"{desc}: '{match.group(0)}'")

    # 3. Stylometric Uniformity (Burstiness)
    is_uniform, std_dev, uniformity_desc = check_stylometric_uniformity(text)
    if is_uniform:
        score_accum += 0.25
        indicators.append(uniformity_desc)

    # 4. PDF Metadata Creator / Producer inspection
    if doc_path and doc_path.exists() and doc_path.suffix.lower() == ".pdf":
        try:
            doc = fitz.open(doc_path)
            meta = doc.metadata or {}
            producer = (meta.get("producer") or "").lower()
            creator = (meta.get("creator") or "").lower()
            author = (meta.get("author") or "").lower()

            for tool in AI_METADATA_PRODUCERS:
                if tool in producer or tool in creator or tool in author:
                    score_accum += 0.60
                    matched_info = meta.get("producer") or meta.get("creator") or meta.get("author")
                    indicators.append(f"AI/synthetic creation software noted in metadata: '{matched_info}'")
                    break
            doc.close()
        except Exception:
            pass

    ai_risk = min(0.99, max(0.0, round(score_accum, 2)))
    is_detected = ai_risk >= 0.50

    if is_detected and indicators:
        summary_rationale = (
            f"Document displays characteristic markers of synthetic or AI-assisted generation: "
            f"{'; '.join(indicators[:3])}."
        )
        finding_tier = FindingTier.INCONSISTENCY if ai_risk >= 0.70 else FindingTier.OBSERVATION

        findings.append(
            Finding(
                finding_id=f"ANM-AI-GEN-{doc_id}",
                tier=finding_tier,
                category=FindingCategory.FORENSIC,
                rule_id="ai_generated_document_detected",
                title="AI-generated document / synthetic content patterns detected",
                evidence=[EvidenceItem(doc_id=doc_id, page=1, bbox=[10, 10, 220, 45], label="AI Generation Forensic Scan")],
                signals=["ai_generated_content", "synthetic_stylometry"],
                strength=FindingStrength.STRONG if ai_risk >= 0.75 else FindingStrength.MODERATE,
                confidence=ai_risk,
                status=FindingStatus.REQUIRES_INVESTIGATION,
                explanation=(
                    f"{summary_rationale} "
                    "Institutional compliance guidelines require that supporting identity and financial instruments "
                    "originate from recognized core banking, employer payroll, or official government portals rather than "
                    "synthetically generated templates."
                ),
                reviewer=ReviewerAction(),
            )
        )
    else:
        summary_rationale = "Authentic financial/identity document styling without synthetic AI generation markers."

    return findings, ai_risk, indicators, summary_rationale
